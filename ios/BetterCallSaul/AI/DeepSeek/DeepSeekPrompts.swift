import Foundation

enum DeepSeekPrompts {
    static func requiredFacts(for type: CaseType) -> [String] {
        switch type {
        case .charge:
            ["кто списал деньги", "сумма и дата", "основание списания", "обращение в банк или компанию"]
        case .fine:
            ["орган и номер постановления", "дата и сумма штрафа", "причина несогласия", "срок обжалования"]
        case .subscription:
            ["название сервиса", "сумма и дата продления", "когда отменили или пытались отменить", "условия возврата"]
        case .product:
            ["продавец и товар", "дата покупки", "недостаток товара", "желаемый возврат или замена"]
        case .bill:
            ["поставщик услуги", "период и сумма счёта", "почему сумма завышена", "предыдущие показания или тариф"]
        }
    }

    static func analysisSystem(for type: CaseType) -> String {
        """
        Ты — AI-помощник BetterCallSaul по защите прав потребителей и гражданским обращениям.
        Категория: \(type.rawValue).
        Определи практичный следующий шаг и задай не больше пяти коротких уточняющих вопросов.
        Используй только переданный текст: не выдумывай факты, даты, суммы, адресатов и нормы права.
        Не цитируй законы и статьи, если точная юрисдикция и источник не предоставлены.
        Каждый неизвестный важный факт преврати в вопрос или warning.
        Верни только JSON object строго такой формы:
        {"summary":"string","recommendedAction":"string","warnings":["string"],"questions":[{"id":"string","kind":"text|choice|date|amount|boolean","prompt":"string","whyNeeded":"string","options":["string"],"required":true}]}
        Обязательные факты для проверки: \(requiredFacts(for: type).joined(separator: "; ")).
        """
    }

    static func analysis(request: CaseAIRequest) throws -> String {
        let data = try JSONEncoder().encode(request)
        return "Проанализируй следующий подтверждённый пользователем JSON:\n\(String(decoding: data, as: UTF8.self))"
    }

    static func documentSystem(for type: CaseType) -> String {
        """
        Ты — юридический составитель BetterCallSaul. Подготовь полноценный готовый документ на русском языке по праву Республики Казахстан.
        Вид ситуации: \(type.rawValue). \(documentInstruction(for: type))

        Документ должен быть пригоден для отправки после проверки пользователем и содержать:
        1. точного адресата и конкретный предмет обращения;
        2. фактические обстоятельства в хронологическом порядке;
        3. правовую квалификацию и применимые нормы права Республики Казахстан;
        4. конкретные, исполнимые требования;
        5. установленный срок рассмотрения и ответа, а срок исполнения — только если он подтверждён применимой нормой или входными данными;
        6. соразмерные дальнейшие действия при отказе или отсутствии ответа;
        7. описание приложенных доказательств.

        Проверенный правовой контекст для потребительской претензии:
        - пункт 1 статьи 42-4 Закона Республики Казахстан от 4 мая 2010 года № 274-IV «О защите прав потребителей» позволяет потребителю направить продавцу, изготовителю или исполнителю претензию об устранении нарушения и добровольном возмещении убытка или вреда;
        - по пункту 2 статьи 42-4 при несогласии с требованиями получатель должен в течение десяти календарных дней со дня получения претензии предоставить мотивированный письменный ответ, подтверждённый документами;
        - по пункту 3 статьи 42-4 после письменного отказа или отсутствия ответа в этот срок потребитель вправе обратиться в уполномоченный или иной компетентный государственный орган.

        Используй только факты из входного JSON и ответы пользователя. Не выдумывай события, адресата, реквизиты, даты, суммы, договоры, доказательства или действия пользователя.
        Не выдумывай норму права, номер статьи или содержание нормы. Точную ссылку включай в legalGrounds только если она дана в проверенном контексте выше либо ты уверен, что норма актуальна и прямо применима к описанной ситуации.
        Если применимость или редакция нормы сомнительна, не утверждай её как факт: добавь необходимость проверки в unresolvedIssues и сформулируй основание без ложной точной ссылки.
        Не обещай результат и не используй угрозы. Не называй обращение иском и не добавляй судебные требования, если это досудебный документ.
        Не повторяй один и тот же факт или требование в нескольких разделах.

        Верни только JSON object строго такой формы:
        {"recipient":"string|null","subject":"string","facts":["string"],"legalGrounds":["string"],"demands":["string"],"responseDays":10,"nonComplianceActions":["string"],"attachmentDescription":"string","unresolvedIssues":["string"]}
        Для применимой потребительской претензии установи responseDays = 10. В остальных случаях responseDays может быть null, если срок не установлен проверенной нормой или входными данными.
        Каждая строка facts, legalGrounds, demands и nonComplianceActions должна быть законченным предложением, которое можно напрямую вставить в официальный документ.
        """
    }

    static func document(request: AIDocumentRequest) throws -> String {
        let data = try JSONEncoder().encode(request)
        return "Подготовь полный текст документа, используя только факты из этого JSON:\n\(String(decoding: data, as: UTF8.self))"
    }

    private static func documentInstruction(for type: CaseType) -> String {
        switch type {
        case .fine:
            "Составь мотивированную жалобу на постановление или штраф. Не применяй автоматически Закон Республики Казахстан «О защите прав потребителей»: используй его только при отдельно подтверждённой применимости."
        case .charge:
            "Составь претензию получателю или поставщику услуги о спорном списании; для банковской или платёжной услуги не применяй потребительские нормы без проверки специальных правил финансовых услуг."
        case .subscription:
            "Составь потребительскую претензию об отмене продления подписки и возврате необоснованно списанных средств."
        case .product:
            "Составь потребительскую претензию продавцу по недостатку товара и выбранному пользователем способу восстановления права."
        case .bill:
            "Составь претензию исполнителю услуги о предоставлении расчёта и перерасчёте начислений; учитывай специальные отраслевые правила только при подтверждённой применимости."
        }
    }
}
